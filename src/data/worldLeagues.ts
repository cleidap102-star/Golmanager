import { KitConfig, LeagueDefinition } from '../types/game';

export interface WorldClubBlueprint {
  id: string;
  leagueId: string;
  federationId: string;
  name: string;
  shortName: string;
  city: string;
  stadiumName: string;
  stadiumCapacity: number;
  primaryColor: string;
  secondaryColor: string;
  homeKit: KitConfig;
  awayKit: KitConfig;
  baseCash: number;
  reputation: number;
  targetOverall: number;
  boardGoalRank: number;
  boardGoalLabel: string;
}

const makeKit = (p: string, s: string, a: string, pattern: KitConfig['pattern']): KitConfig => ({
  primary: p,
  secondary: s,
  accent: a,
  pattern,
});

function c(
  id: string,
  leagueId: string,
  federationId: string,
  name: string,
  shortName: string,
  city: string,
  stadiumName: string,
  stadiumCapacity: number,
  primaryColor: string,
  secondaryColor: string,
  targetOverall: number,
  boardGoalRank: number,
  boardGoalLabel: string,
  pattern: KitConfig['pattern'] = 'LISO',
): WorldClubBlueprint {
  const baseCash = Math.round((targetOverall - 54) * 1_150_000);
  return {
    id,
    leagueId,
    federationId,
    name,
    shortName,
    city,
    stadiumName,
    stadiumCapacity,
    primaryColor,
    secondaryColor,
    homeKit: makeKit(primaryColor, secondaryColor, '#F8FAFC', pattern),
    awayKit: makeKit('#F8FAFC', primaryColor, secondaryColor, 'FAIXA'),
    baseCash: Math.max(3_500_000, baseCash),
    reputation: Math.min(95, targetOverall + 9),
    targetOverall,
    boardGoalRank,
    boardGoalLabel,
  };
}

